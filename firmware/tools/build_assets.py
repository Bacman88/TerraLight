"""Pack the web panel into a C header.

web/index.html + style.css + app.js  →  one HTML  →  gzip  →  src/web/assets.h

Runs automatically before every PlatformIO build (extra_scripts = pre:...)
and can also be run by hand:  python tools/build_assets.py
The generated header is committed, so the firmware also builds without Python.
"""
import gzip
import os
import re

try:  # PlatformIO / SCons
    Import("env")  # noqa: F821
    PROJECT_DIR = env["PROJECT_DIR"]  # noqa: F821
except NameError:  # standalone
    PROJECT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB_DIR = os.path.join(PROJECT_DIR, "web")
OUT_FILE = os.path.join(PROJECT_DIR, "src", "web", "assets.h")


def read(name):
    with open(os.path.join(WEB_DIR, name), encoding="utf-8") as f:
        return f.read()


def build_html():
    html = read("index.html")
    css = read("style.css")
    js = read("app.js")
    html = html.replace('<link rel="stylesheet" href="style.css">', "<style>\n" + css + "\n</style>")
    html = html.replace('<script src="app.js"></script>', "<script>\n" + js + "\n</script>")
    # Light minification: drop HTML comments and indentation.
    html = re.sub(r"<!--(?!\[).*?-->", "", html, flags=re.S)
    html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
    return html


def to_c_array(data, per_line=20):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join("0x%02x" % b for b in data[i : i + per_line]) + ",")
    return "\n".join(lines)


def main():
    html = build_html().encode("utf-8")
    gz = bytearray(gzip.compress(html, compresslevel=9, mtime=0))  # mtime=0 → reproducible output
    gz[9] = 0xFF  # OS byte: newer Pythons write the host OS, which differs between machines
    header = (
        "// AUTO-GENERATED by tools/build_assets.py — do not edit.\n"
        "// Source: web/index.html, web/style.css, web/app.js\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        "// Panel HTML, gzip (%d bytes raw → %d bytes)\n"
        "static const uint8_t PANEL_HTML_GZ[] PROGMEM = {\n%s\n};\n"
        "static const size_t PANEL_HTML_GZ_LEN = sizeof(PANEL_HTML_GZ);\n"
    ) % (len(html), len(gz), to_c_array(gz))

    old = None
    if os.path.exists(OUT_FILE):
        with open(OUT_FILE, encoding="utf-8") as f:
            old = f.read()
    if old != header:  # don't touch the file if nothing changed (no needless rebuilds)
        with open(OUT_FILE, "w", encoding="utf-8", newline="\n") as f:
            f.write(header)
    print("[assets] panel: %d B → %d B gzip" % (len(html), len(gz)))


main()
